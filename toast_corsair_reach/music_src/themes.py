def minor_v(root):
    """In a minor key: the dominant chord major (its raised third is the leading tone)."""
    return "M" if root % 7 == 4 else None


def chords_only(bars):
    """The same bars with the melody taken out (for parts that only need the harmony)."""
    return [dict(notes=[(None, sum(b for _, b in tb["notes"]))], chords=tb["chords"]) for tb in bars]


def held(bars, beats=4):
    """The bars as one held chord each: the first chord's root for the whole bar."""
    return [dict(notes=tb["notes"], chords=[(tb["chords"][0][0], beats)]) for tb in bars]
