"""The three world themes, in scale degrees (0 = the key's tonic, 7 its octave), so one theme plays in any key or
mode. Each bar: its notes (degree or None for a rest, beats) and its chords (root degree, beats). A and B are
eight bars each."""


def _bars(rows):
    return [dict(notes=n, chords=c) for n, c in rows]


